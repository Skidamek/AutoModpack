#!/usr/bin/env bash
# Rebuilds the committed Windows native from source and refreshes its receipt.
#
# Same-toolchain rebuilds are byte-identical: the build flags fix the PE timestamp and
# image base, and the output name must stay win_natives.dll - mingw embeds it as the DLL's
# internal export name, and WindowsNatives extracts the resource under the same name.
# Cross-toolchain builds are NOT byte-identical, so the
# commit ships a receipt (natives-receipt.txt) naming the exact sources and DLL it was
# built from; CI compiles the C with mingw to prove the sources build and the receipt
# check proves the committed DLL was not left behind by a source edit.
#
# Requires: x86_64-w64-mingw32-gcc (mingw-w64) on PATH and JAVA_HOME pointing at
# a JDK (any version; only jni.h is used).
set -euo pipefail

c="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
repo="$(cd "$c/../../../.." && pwd -P)"
dll="core/src/main/resources/natives/windows-x86_64/win_natives.dll"

command -v x86_64-w64-mingw32-gcc >/dev/null || { echo "error: x86_64-w64-mingw32-gcc not on PATH (install mingw-w64)" >&2; exit 1; }
: "${JAVA_HOME:?error: JAVA_HOME must point at a JDK (jni.h is required)}"

work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT
x86_64-w64-mingw32-gcc -c -O0 -fno-PIC -fno-ident -o "$work/pe_reloc.o" "$c/pe_reloc.c"
x86_64-w64-mingw32-gcc -shared -s -Os -fno-ident -fPIC -fno-stack-protector -fno-asynchronous-unwind-tables -fno-unwind-tables -nostdlib -Wl,--gc-sections -Wl,--enable-reloc-section -Wl,--dynamicbase -Wl,--high-entropy-va -Wl,--no-insert-timestamp -Wl,--image-base,0x6BCB5F440000 -Wl,-e,DllMain -Wl,-u,win_natives_keep -I "$c" -I "$JAVA_HOME/include" -o "$repo/$dll" "$c/windows_file_stat.c" "$c/windows_lock_probe.c" "$work/pe_reloc.o" -lkernel32
# The keep symbol is the GC root that keeps the base relocation section alive; without it the DLL
# still links but cannot rebase under ASLR, and fails to load - so an empty reloc directory is fatal.
relocSize=$(x86_64-w64-mingw32-objdump -p "$repo/$dll" | awk '/Base Relocation Directory/ {print $3; found=1} END {if (!found) exit 1}')
[ -n "$relocSize" ] && [ "$relocSize" != "00000000" ] || { echo "error: $dll has an empty base relocation directory; it would fail to load under ASLR" >&2; exit 1; }
cd "$repo"
{
	echo "# Generated by core/src/main/c/rebuild-windows-natives.sh - commit together with the DLL it names."
	sha256sum core/src/main/c/windows_file_stat.c core/src/main/c/windows_lock_probe.c core/src/main/c/windows_jni_path.h core/src/main/c/pe_reloc.c core/src/main/c/jni_md.h "$dll"
} > core/src/main/c/natives-receipt.txt
cat core/src/main/c/natives-receipt.txt
